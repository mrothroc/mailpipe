// commandRunner is the shared shape of the Graph and read-only test
// environments' run methods, so verdict checks can be shared.
type commandRunner interface {
	run(args ...string) (int, string, string)
}

// attachmentVerdictOut renders one message's verdicts as the CLI shows them,
// so a workflow step can be compared with the state that preceded it. A failed
// query fails the test instead of masquerading as empty output.
func attachmentVerdictOut(t *testing.T, r commandRunner, n string) string {
	t.Helper()
	code, out, stderr := r.run("verdicts", n)
	if code != 0 {
		t.Fatalf("verdicts %s: exit %d: %s", n, code, stderr)
	}
	return out
}

type attachmentMailState struct {
	read, hasAttachments, body bool
}

// attachmentMailStateOf reads the stored local state a content or filing step
// must never mutate on its own.
func attachmentMailStateOf(t *testing.T, e *env, n string) attachmentMailState {
	t.Helper()
	cfg, err := config.Load(config.DefaultPath())
	if err != nil {
		t.Fatal(err)
	}
	s, err := store.OpenAccount(context.Background(), e.db, cfg.Account())
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	num, err := strconv.ParseInt(n, 10, 64)
	if err != nil {
		t.Fatal(err)
	}
	m, err := s.GetMessage(context.Background(), mailbox.LocalRef{AccountID: cfg.Account().ID, N: num})
	if err != nil {
		t.Fatal(err)
	}
	return attachmentMailState{m.State.Metadata.IsRead, m.State.Metadata.HasAttachments, m.Body != nil}
}

// attachmentInlineImageRow picks the listing's one inline image and proves the
// listing's digest describes the generated bytes, not a filename guess.
func attachmentInlineImageRow(t *testing.T, rows []map[string]any, want []byte) map[string]any {
	t.Helper()
	digest := sha256.Sum256(want)
	var imageRows []map[string]any
	for _, row := range rows {
		if row["kind"] == "inline_image" {
			imageRows = append(imageRows, row)
		}
	}
	if len(imageRows) != 1 {
		t.Fatalf("want exactly one inline image row: %v", rows)
	}
	if imageRows[0]["sha256"] != hex.EncodeToString(digest[:]) {
		t.Fatalf("listing digest %v, want %s", imageRows[0], hex.EncodeToString(digest[:]))
	}
	return imageRows[0]
}

// The one-off workflow on the Microsoft 365 path: inspect a synthetic message,
// extract the selected inline image byte-for-byte, then file the same message
// through a hand-written save manifest with no templates. Extraction must leave
// the filing verdict and mail state untouched; only the authorized save writes
// a PDF and records filing:saved, and the PDF must contain the whole image.
func TestAttachmentInspectExtractOneOffFilingEndToEnd(t *testing.T) {
	tools := requireImageTools(t)
	fixture := imageFixture{600, 3600, 0, ""}
	png := imageFixturePNG(fixture)

	e, root := savable(t)
	e.graph.mime["g2"] = imageFixtureMIME([]imageFixture{fixture}, "", "")
	_, ls, _ := e.run("ls", "--from", "friend")
	n := firstN(t, ls)

	beforeVerdicts := attachmentVerdictOut(t, e, n)
	beforeState := attachmentMailStateOf(t, e, n)

	row := attachmentInlineImageRow(t, attachmentList(t, e, n), png)
	outDir := attachmentPrivateDir(t)

	// Check mode validates content and destination but writes nothing.
	code, out, stderr := e.run("attachments", "extract", n, "--part", row["part"].(string), "--out-dir", outDir, "--json")
	if code != 0 || !strings.Contains(out, `"status":"ready"`) {
		t.Fatalf("check %d %s %s", code, out, stderr)
	}
	if entries, _ := os.ReadDir(outDir); len(entries) != 0 {
		t.Fatalf("check mode wrote output: %v", entries)
	}

	// Execute streams the exact decoded bytes into a private 0600 file.
	code, out, stderr = e.run("attachments", "extract", n, "--part", row["part"].(string), "--out-dir", outDir, "--execute", "--json")
	if code != 0 {
		t.Fatalf("extract %d %s %s", code, out, stderr)
	}
	extracted := attachmentRows(t, out)[0]
	savedPath := extracted["saved_path"].(string)
	saved, err := os.ReadFile(savedPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(saved, png) {
		t.Fatalf("extracted bytes differ from generated image: got %d want %d", len(saved), len(png))
	}
	if fi, err := os.Stat(savedPath); err != nil || fi.Mode().Perm() != 0o600 {
		t.Fatalf("extracted file mode %v %v", fi, err)
	}

	// Raw extraction must leave the filing verdict and mail state exactly as
	// they were: no filing:saved, no read-state or attachment-flag change.
	if got := attachmentVerdictOut(t, e, n); got != beforeVerdicts {
		t.Fatalf("extraction changed verdicts:\nbefore %q\nafter  %q", beforeVerdicts, got)
	}
	if strings.Contains(beforeVerdicts, "filing") {
		t.Fatalf("fixture began with a filing verdict: %q", beforeVerdicts)
	}
	if after := attachmentMailStateOf(t, e, n); after != beforeState {
		t.Fatalf("extraction mutated local mail state: before %+v after %+v", beforeState, after)
	}
	if len(e.graph.moved) != 0 {
		t.Fatalf("extraction moved mail: %v", e.graph.moved)
	}
	if len(e.rendered) != 0 {
		t.Fatalf("raw extraction rendered a document: %v", e.rendered)
	}

	// One-off filing uses a hand-written manifest; no templates are consulted.
	m := manifest(t, e, "{g2}\tArchive/Records/2026\t2026-11-03_Complete_Image_Record.pdf")

	// The check writes no PDF and records no signed-off filing.
	code, out, errOut := runImageSave(t, e, tools.chrome, "save", "--manifest", m, "--root", root)
	if code != 0 || !strings.Contains(out, "\twould_save\t") || !strings.Contains(errOut, "check only, nothing written") {
		t.Fatalf("save check %d %s %s", code, out, errOut)
	}
	if _, err := os.Stat(root); !os.IsNotExist(err) {
		t.Fatal("save check created the filing root")
	}
	if got := attachmentVerdictOut(t, e, n); strings.Contains(got, "saved") {
		t.Fatalf("save check recorded a signed-off filing: %q", got)
	}

	// Execute is the only step that writes the PDF and records filing:saved.
	code, out, errOut = runImageSave(t, e, tools.chrome, "save", "--manifest", m, "--root", root, "--execute")
	if code != 0 || !strings.Contains(out, "\tsaved\t") {
		t.Fatalf("save execute %d %s %s", code, out, errOut)
	}
	pdfPath := filepath.Join(root, "Archive/Records/2026/2026-11-03_Complete_Image_Record.pdf")
	pdf, err := os.ReadFile(pdfPath)
	if err != nil {
		t.Fatal(err)
	}
	if fi, err := os.Stat(pdfPath); err != nil || fi.Mode().Perm() != 0o600 {
		t.Fatalf("filed PDF mode %v %v", fi, err)
	}
	if got := attachmentVerdictOut(t, e, n); !strings.Contains(got, "saved") {
		t.Fatalf("executed save did not record filing:saved: %q", got)
	}
	if after := attachmentMailStateOf(t, e, n); after != beforeState {
		t.Fatalf("executed save mutated local mail state: before %+v after %+v", beforeState, after)
	}
	if len(e.graph.moved) != 0 {
		t.Fatalf("executed save moved mail: %v", e.graph.moved)
	}
	// The raster oracle proves the filed PDF shows the complete image.
	inspectImagePDF(t, tools, pdf, []imageFixture{fixture}, true)
}

// The same workflow on the supported read-only provider path: the real local
// IMAP adapter lists and extracts the exact generated bytes while preserving
// unread state, and the read-only pilot still refuses save execution.
func TestAttachmentReadOnlyProviderExtractAndSaveRefusal(t *testing.T) {
	fixture := imageFixture{600, 3600, 0, ""}
	png := imageFixturePNG(fixture)
	raw := "From: records@example.org\r\nSubject: Complete image fixture\r\nContent-Type: image/png\r\nContent-Transfer-Encoding: base64\r\n\r\n" +
		base64.StdEncoding.EncodeToString(png)

	e := newYahooEnv(t)
	e.server.mu.Lock()
	e.server.messages[0].source = raw
	e.server.mu.Unlock()
	e.ok("auth", "login")
	e.ok("sync", "--folder", "inbox")

	beforeVerdicts := attachmentVerdictOut(t, e, "1")

	code, out, stderr := e.run("attachments", "list", "1", "--json")
	if code != 0 {
		t.Fatalf("read-only list %d %s %s", code, out, stderr)
	}
	row := attachmentInlineImageRow(t, attachmentRows(t, out), png)
	outDir := attachmentPrivateDir(t)
	code, out, stderr = e.run("attachments", "extract", "1", "--part", row["part"].(string), "--out-dir", outDir, "--execute", "--json")
	if code != 0 {
		t.Fatalf("read-only extract %d %s %s", code, out, stderr)
	}
	extracted := attachmentRows(t, out)[0]
	saved, err := os.ReadFile(extracted["saved_path"].(string))
	if err != nil || !bytes.Equal(saved, png) {
		t.Fatalf("read-only extracted bytes differ: %v len=%d want=%d", err, len(saved), len(png))
	}
	e.server.mu.Lock()
	flags, fetches := e.server.messages[0].flags, e.server.sourceFetches
	e.server.mu.Unlock()
	if flags != "" || fetches < 2 {
		t.Fatalf("read-only extraction changed state: flags=%q fetches=%d", flags, fetches)
	}
	if got := attachmentVerdictOut(t, e, "1"); got != beforeVerdicts {
		t.Fatalf("read-only extraction changed verdicts:\nbefore %q\nafter  %q", beforeVerdicts, got)
	}
	e.server.audit(t)

	// A one-off save manifest is accepted as a check, but the read-only pilot
	// refuses every execution and writes nothing, touches no store/credential/
	// provider, and asks for no model.
	root := filepath.Join(e.dir, "documents")
	if err := os.Mkdir(root, 0o700); err != nil {
		t.Fatal(err)
	}
	m := filepath.Join(e.dir, "manifest.tsv")
	if err := os.WriteFile(m, []byte("n\tfolder\tname\n1\t.\t2026-11-03_Complete_Image_Record.pdf\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	code, out, stderr = e.run("save", "--manifest", m, "--root", root)
	if code != 0 || !strings.Contains(out, "would_save") {
		t.Fatalf("read-only save check %d %s %s", code, out, stderr)
	}
	opens, clients, calls := e.opens, e.clients, e.runner.calls
	code, out, stderr = e.run("save", "--manifest", m, "--root", root, "--execute")
	if code == 0 {
		t.Fatalf("read-only provider permitted save --execute: %s %s", out, stderr)
	}
	if e.opens != opens || e.clients != clients || e.runner.calls != calls {
		t.Fatalf("refused save performed effects: opens %d->%d clients %d->%d calls %d->%d", opens, e.opens, clients, e.clients, calls, e.runner.calls)
	}
	if entries, _ := os.ReadDir(root); len(entries) != 0 {
		t.Fatalf("refused save wrote files: %v", entries)
	}
	if got := attachmentVerdictOut(t, e, "1"); got != beforeVerdicts {
		t.Fatalf("refused save changed verdicts:\nbefore %q\nafter  %q", beforeVerdicts, got)
	}
	e.server.mu.Lock()
	readState := e.server.messages[0].flags
	e.server.mu.Unlock()
	if readState != "" {
		t.Fatalf("refused save changed read state: %q", readState)
	}
	if e.models != 0 {
		t.Fatalf("read-only workflow made %d model calls", e.models)
	}
	e.server.audit(t)
}
